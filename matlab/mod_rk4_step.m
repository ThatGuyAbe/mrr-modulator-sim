function [ar,ai,Nn,Tn,Vn] = mod_rk4_step(ar,ai,Nv,Tv,Vv, ...
        Ein, Vext, dtau, ...
        dw_n, dw_NL_s, dw_mod_n, ...
        mu_n, glin_n, cTPA_n, cFCA_n, cFCg_n, ...
        cTh_n, g0, iTFC_n, iTTH_n, dnN, dnT, iTRC_n)
% one 4th-order runge-kutta step of the 5-state model, state [ar, ai, DN, DT, Vpn]:
%   ar, ai  real and imaginary parts of the cavity amplitude a
%   DN      free-carrier density (m^-3)
%   DT      temperature rise (K)
%   Vpn     junction voltage (V)
% Ein (sqrt(W)) and Vext (V) are held over the step. time is tau = gamma_0 * t.
    h = 0.5 * dtau;
    [r1,i1,n1,t1,v1] = cavity_rhs(ar, ai, Nv, Tv, Vv, ...
        Ein, Vext, dw_n, dw_NL_s, dw_mod_n, ...
        mu_n, glin_n, cTPA_n, cFCA_n, cFCg_n, ...
        cTh_n, g0, iTFC_n, iTTH_n, dnN, dnT, iTRC_n);
    [r2,i2,n2,t2,v2] = cavity_rhs( ...
        ar + h*r1, ai + h*i1, max(Nv + h*n1, 0), max(Tv + h*t1, 0), Vv + h*v1, ...
        Ein, Vext, dw_n, dw_NL_s, dw_mod_n, ...
        mu_n, glin_n, cTPA_n, cFCA_n, cFCg_n, ...
        cTh_n, g0, iTFC_n, iTTH_n, dnN, dnT, iTRC_n);
    [r3,i3,n3,t3,v3] = cavity_rhs( ...
        ar + h*r2, ai + h*i2, max(Nv + h*n2, 0), max(Tv + h*t2, 0), Vv + h*v2, ...
        Ein, Vext, dw_n, dw_NL_s, dw_mod_n, ...
        mu_n, glin_n, cTPA_n, cFCA_n, cFCg_n, ...
        cTh_n, g0, iTFC_n, iTTH_n, dnN, dnT, iTRC_n);
    [r4,i4,n4,t4,v4] = cavity_rhs( ...
        ar + dtau*r3, ai + dtau*i3, max(Nv + dtau*n3, 0), max(Tv + dtau*t3, 0), Vv + dtau*v3, ...
        Ein, Vext, dw_n, dw_NL_s, dw_mod_n, ...
        mu_n, glin_n, cTPA_n, cFCA_n, cFCg_n, ...
        cTh_n, g0, iTFC_n, iTTH_n, dnN, dnT, iTRC_n);
    s  = dtau / 6;
    ar = ar + s * (r1 + 2*r2 + 2*r3 + r4);
    ai = ai + s * (i1 + 2*i2 + 2*i3 + i4);
    Nn = max(Nv + s * (n1 + 2*n2 + 2*n3 + n4), 0);
    Tn = max(Tv + s * (t1 + 2*t2 + 2*t3 + t4), 0);
    Vn = Vv + s * (v1 + 2*v2 + 2*v3 + v4);
end

function [dar, dai, dN, dTv, dVpn] = cavity_rhs( ...
        ar, ai, Nv, Tv, Vpn, ...
        Ein, Vext, ...
        dw_n, dw_NL_s, dw_mod_n, ...
        mu_n, glin_n, cTPA_n, cFCA_n, cFCg_n, ...
        cTh_n, g0, iTFC_n, iTTH_n, dnN, dnT, iTRC_n)
% right-hand side in normalized time. giron castro (2024) eqs. 1-6 with the voltage
% modulation of de cea (2019) eqs. 1-3. the total detuning is
%   dw_tot = dw_n + dw_NL_s*(DN*dn_dN + DT*dn_dT) + dw_mod_n*Vpn,  dw_mod_n = -dW0_dVpn/gamma_0
    a2 = ar^2 + ai^2;
    % detuning
    dw_NL  = dw_NL_s * (Nv*dnN + Tv*dnT);   % carriers and heat
    dw_mod = dw_mod_n * Vpn;                  % voltage modulation
    dw_tot = dw_n + dw_NL + dw_mod;
    % total cavity loss, 1 = (gamma_lin + gamma_coup)/gamma_0
    gTPA = cTPA_n * a2;
    gFCA = cFCA_n * Nv;
    gtot = 1 + gTPA + gFCA;
    % cavity field, cw input enters the imaginary part
    dar = -dw_tot * ai  -  gtot * ar;
    dai =  dw_tot * ar  -  gtot * ai  +  mu_n * Ein;
    % free carriers
    dN = -iTFC_n * Nv  +  cFCg_n * a2^2;
    % temperature, heated by the absorbed power
    Pn  = (glin_n + gTPA + gFCA) * a2;       % absorbed power (normalized)
    dTv = -iTTH_n * Tv  +  cTh_n * g0 * Pn;
    % junction voltage, first-order rc filter
    dVpn = iTRC_n * (Vext - Vpn);
end
